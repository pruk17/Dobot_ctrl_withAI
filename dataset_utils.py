# -*- coding: utf-8 -*-
"""
dataset_utils.py
----------------
Everything that touches the dataset folder lives here, so no UI code has to know
the layout on disk.

    dataset/
        images/train/*.jpg
        images/val/*.jpg
        labels/train/*.txt   YOLO format: class_id cx cy w h, normalised 0-1
        labels/val/*.txt
        classes.txt          one class name per line; the line number is the class id
        data.yaml            config file for ultralytics YOLO
        model/best.pt        the trained model, copied here so it is easy to find

classes.txt is the single source of truth for class ids: the labels written by the
labelling canvas and the names written into data.yaml both come from it.
"""

import os
import random
import shutil

import cv2
import numpy as np
import yaml

BASE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "dataset")
IMAGES_TRAIN = os.path.join(BASE_DIR, "images", "train")
IMAGES_VAL = os.path.join(BASE_DIR, "images", "val")
LABELS_TRAIN = os.path.join(BASE_DIR, "labels", "train")
LABELS_VAL = os.path.join(BASE_DIR, "labels", "val")
CLASSES_FILE = os.path.join(BASE_DIR, "classes.txt")
DATA_YAML = os.path.join(BASE_DIR, "data.yaml")
MODEL_DIR = os.path.join(BASE_DIR, "model")
MODEL_PATH = os.path.join(MODEL_DIR, "best.pt")
AUG_CONFIG = os.path.join(BASE_DIR, "augment.json")

# Filenames containing this marker are extra images generated by augment_utils, not
# photographs taken by the operator. They are hidden from the labelling UI and are
# rebuilt from scratch before every training run. YOLO still reads them, because it
# scans the folder itself.
AUG_MARK = "__aug"


def is_augmented(name):
    return AUG_MARK in os.path.basename(name)


def save_image(path, image):
    """Write an image in a way that also works when the path contains non ASCII
    characters. cv2.imwrite fails silently on those, which would leave the dataset
    short of images with no error message."""
    ext = os.path.splitext(path)[1] or ".jpg"
    ok, buf = cv2.imencode(ext, image)
    if not ok:
        return False
    buf.tofile(path)
    return True


def read_image(path):
    """Counterpart of save_image for reading paths with non ASCII characters."""
    data = np.fromfile(path, dtype=np.uint8)
    if data.size == 0:
        return None
    return cv2.imdecode(data, cv2.IMREAD_COLOR)


def ensure_dirs():
    for d in [IMAGES_TRAIN, IMAGES_VAL, LABELS_TRAIN, LABELS_VAL, MODEL_DIR]:
        os.makedirs(d, exist_ok=True)
    if not os.path.exists(CLASSES_FILE):
        with open(CLASSES_FILE, "w", encoding="utf-8") as f:
            f.write("")


def load_classes():
    ensure_dirs()
    with open(CLASSES_FILE, "r", encoding="utf-8") as f:
        classes = [line.strip() for line in f if line.strip()]
    return classes


def save_classes(classes):
    ensure_dirs()
    with open(CLASSES_FILE, "w", encoding="utf-8") as f:
        for c in classes:
            f.write(c + "\n")


def add_class(name):
    classes = load_classes()
    if name not in classes:
        classes.append(name)
        save_classes(classes)
    return classes


def list_images(folder, include_augmented=False):
    exts = (".jpg", ".jpeg", ".png", ".bmp")
    if not os.path.isdir(folder):
        return []
    names = [f for f in os.listdir(folder) if f.lower().endswith(exts)]
    if not include_augmented:
        names = [f for f in names if not is_augmented(f)]
    return sorted(names)


def label_path_for_image(image_path):
    """Map an image path to the matching label path in the train or val folder."""
    folder = os.path.dirname(image_path)
    base = os.path.splitext(os.path.basename(image_path))[0]
    if folder == IMAGES_TRAIN:
        return os.path.join(LABELS_TRAIN, base + ".txt")
    elif folder == IMAGES_VAL:
        return os.path.join(LABELS_VAL, base + ".txt")
    else:
        # Fallback: keep the label next to the image.
        return os.path.join(folder, base + ".txt")


def unlabeled_images(folder=None):
    """Return the images that have no label file, or an empty one."""
    folders = [folder] if folder else [IMAGES_TRAIN, IMAGES_VAL]
    result = []
    for fd in folders:
        for img in list_images(fd):
            img_path = os.path.join(fd, img)
            lbl_path = label_path_for_image(img_path)
            if not os.path.exists(lbl_path) or os.path.getsize(lbl_path) == 0:
                result.append(img_path)
    return result


def all_images():
    result = []
    for fd in [IMAGES_TRAIN, IMAGES_VAL]:
        for img in list_images(fd):
            result.append(os.path.join(fd, img))
    return result


def rebalance_train_val(val_ratio=0.2, seed=42):
    """Pool every image again and re-split it into train and val.

    Run this before training to make sure a validation set exists. Labels follow
    their image. With fewer than five images no validation split is made, because a
    single-image val set is meaningless.
    """
    ensure_dirs()
    imgs = all_images()
    if len(imgs) == 0:
        return 0, 0
    rnd = random.Random(seed)
    rnd.shuffle(imgs)
    n_val = max(1, int(len(imgs) * val_ratio)) if len(imgs) >= 5 else 0
    val_set = set(imgs[:n_val])

    for img_path in imgs:
        lbl_path = label_path_for_image(img_path)
        base = os.path.basename(img_path)
        lbl_base = os.path.basename(lbl_path) if os.path.exists(lbl_path) else None
        target_img_dir = IMAGES_VAL if img_path in val_set else IMAGES_TRAIN
        target_lbl_dir = LABELS_VAL if img_path in val_set else LABELS_TRAIN

        new_img_path = os.path.join(target_img_dir, base)
        if os.path.abspath(new_img_path) != os.path.abspath(img_path):
            shutil.move(img_path, new_img_path)

        if lbl_base and os.path.exists(lbl_path):
            new_lbl_path = os.path.join(target_lbl_dir, lbl_base)
            if os.path.abspath(new_lbl_path) != os.path.abspath(lbl_path):
                shutil.move(lbl_path, new_lbl_path)

    n_train = len(imgs) - len(val_set)
    return n_train, len(val_set)


def write_data_yaml():
    """Write the ultralytics config. Falls back to the train split for validation
    when no val images exist, otherwise training would abort."""
    ensure_dirs()
    classes = load_classes()
    data = {
        "path": BASE_DIR,
        "train": "images/train",
        "val": "images/val" if len(list_images(IMAGES_VAL)) > 0 else "images/train",
        "names": {i: c for i, c in enumerate(classes)},
    }
    with open(DATA_YAML, "w", encoding="utf-8") as f:
        yaml.safe_dump(data, f, allow_unicode=True, sort_keys=False)
    return DATA_YAML
